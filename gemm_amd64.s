// func kernel6x16(a *float32, lda int, b *float32, ldb int, c *float32, ldc int, k int)
TEXT ·kernel6x16(SB), NOSPLIT, $0-56
	MOVQ a+0(FP), SI
	MOVQ lda+8(FP), R8
	MOVQ b+16(FP), DI
	MOVQ ldb+24(FP), R9
	MOVQ c+32(FP), DX
	MOVQ ldc+40(FP), R10
	MOVQ k+48(FP), CX
	SHLQ $2, R8
	SHLQ $2, R9
	SHLQ $2, R10
	LEAQ (R8)(R8*2), R11
	LEAQ (R8)(R8*4), R12
	LEAQ (R10)(R10*2), R13
	LEAQ (R10)(R10*4), BX

	VMOVUPS (DX), Y0
	VMOVUPS 32(DX), Y1
	VMOVUPS (DX)(R10*1), Y2
	VMOVUPS 32(DX)(R10*1), Y3
	VMOVUPS (DX)(R10*2), Y4
	VMOVUPS 32(DX)(R10*2), Y5
	VMOVUPS (DX)(R13*1), Y6
	VMOVUPS 32(DX)(R13*1), Y7
	VMOVUPS (DX)(R10*4), Y8
	VMOVUPS 32(DX)(R10*4), Y9
	VMOVUPS (DX)(BX*1), Y10
	VMOVUPS 32(DX)(BX*1), Y11

loop:
	VMOVUPS      (DI), Y12
	VMOVUPS      32(DI), Y13
	VBROADCASTSS (SI), Y14
	VFMADD231PS  Y12, Y14, Y0
	VFMADD231PS  Y13, Y14, Y1
	VBROADCASTSS (SI)(R8*1), Y15
	VFMADD231PS  Y12, Y15, Y2
	VFMADD231PS  Y13, Y15, Y3
	VBROADCASTSS (SI)(R8*2), Y14
	VFMADD231PS  Y12, Y14, Y4
	VFMADD231PS  Y13, Y14, Y5
	VBROADCASTSS (SI)(R11*1), Y15
	VFMADD231PS  Y12, Y15, Y6
	VFMADD231PS  Y13, Y15, Y7
	VBROADCASTSS (SI)(R8*4), Y14
	VFMADD231PS  Y12, Y14, Y8
	VFMADD231PS  Y13, Y14, Y9
	VBROADCASTSS (SI)(R12*1), Y15
	VFMADD231PS  Y12, Y15, Y10
	VFMADD231PS  Y13, Y15, Y11
	ADDQ         $4, SI
	ADDQ         R9, DI
	DECQ         CX
	JNZ          loop

	VMOVUPS Y0, (DX)
	VMOVUPS Y1, 32(DX)
	VMOVUPS Y2, (DX)(R10*1)
	VMOVUPS Y3, 32(DX)(R10*1)
	VMOVUPS Y4, (DX)(R10*2)
	VMOVUPS Y5, 32(DX)(R10*2)
	VMOVUPS Y6, (DX)(R13*1)
	VMOVUPS Y7, 32(DX)(R13*1)
	VMOVUPS Y8, (DX)(R10*4)
	VMOVUPS Y9, 32(DX)(R10*4)
	VMOVUPS Y10, (DX)(BX*1)
	VMOVUPS Y11, 32(DX)(BX*1)
	VZEROUPPER
	RET

